# Generates tables.go: python3 gen_unorm.py
import unicodedata, sys
ud = unicodedata
decomp = []   # (c, a, b)
for c in range(0x110000):
    if 0xAC00 <= c <= 0xD7A3: continue
    d = ud.decomposition(chr(c))
    if not d or d.startswith('<'): continue
    parts = [int(x,16) for x in d.split()]
    a = parts[0]; b = parts[1] if len(parts) > 1 else 0
    assert len(parts) <= 2
    decomp.append((c, a, b))
comp = []
for c, a, b in decomp:
    if b == 0: continue
    if ud.normalize('NFC', chr(c)) != chr(c): continue
    comp.append((a, b, c))
comp.sort()
ccc = []
start = None
prev = None
for c in range(0x110000):
    v = ud.combining(chr(c))
    if v:
        if start is not None and prev == (c-1, v):
            prev = (c, v); continue
        if start is not None: ccc.append((start, prev[0], prev[1]))
        start = c; prev = (c, v)
    else:
        if start is not None: ccc.append((start, prev[0], prev[1])); start=None; prev=None
if start is not None: ccc.append((start, prev[0], prev[1]))
out = ['// Code generated by gen_unorm.py from Python %s unicodedata (Unicode %s); DO NOT EDIT.' % (sys.version.split()[0], ud.unidata_version), '', 'package unorm', '']
out.append('// decompositions: code point, first and second (0 if none) part of its')
out.append('// canonical decomposition.')
out.append('var decompositions = [...][3]rune{')
for c,a,b in decomp: out.append('\t{0x%X, 0x%X, 0x%X},' % (c,a,b))
out.append('}')
out.append('')
out.append('// compositions: primary composites by their two parts.')
out.append('var compositions = [...][3]rune{')
for a,b,c in comp: out.append('\t{0x%X, 0x%X, 0x%X},' % (a,b,c))
out.append('}')
out.append('')
out.append('// combiningClasses: ranges of code points with a nonzero canonical')
out.append('// combining class.')
out.append('var combiningClasses = [...]struct {')
out.append('\tlo, hi rune')
out.append('\tclass uint8')
out.append('}{')
for a,b,v in ccc: out.append('\t{0x%X, 0x%X, %d},' % (a,b,v))
out.append('}')
open('tables.go','w').write('\n'.join(out)+'\n')
print(len(decomp), len(comp), len(ccc), ud.unidata_version)
