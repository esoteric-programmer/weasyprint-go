# Generates casing_tables.go: python3 gen_casing.py
# The unconditional multi-character case mappings of SpecialCasing.txt, as
# Python's str.upper/str.title implement them.
import sys, unicodedata
out = ['// Code generated by gen_casing.py from Python %d.%d unicodedata (Unicode %s); DO NOT EDIT.' % (sys.version_info[0], sys.version_info[1], unicodedata.unidata_version), '', 'package unorm', '']
for name, fn in (('specialUpper', str.upper), ('specialTitle', str.title)):
    out.append('var %s = map[rune]string{' % name)
    for cp in range(0x110000):
        c = chr(cp)
        m = fn(c)
        if len(m) > 1:
            out.append('\t0x%04x: "%s",' % (cp, ''.join('\\u%04x' % ord(x) if ord(x) > 0x7f else x for x in m)))
    out.append('}')
    out.append('')
open('casing_tables.go', 'w').write('\n'.join(out))
