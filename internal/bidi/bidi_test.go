func TestLevelsFribidi(t *testing.T) {
	for _, c := range fribidiCases {
		base := 0
		if c.rtl {
			base = 1
		}
		got := Levels([]rune(c.text), base)
		for i, r := range []rune(c.text) {
			switch ClassOf(r) {
			case LRE, RLE, LRO, RLO, PDF, BN:
				got[i] = c.levels[i]
			}
		}
		if !reflect.DeepEqual(got, c.levels) {
			t.Errorf("%q rtl=%v: got %v, want %v", c.text, c.rtl, got, c.levels)
		}
	}
}

func TestReorder(t *testing.T) {
	if got := Reorder([]uint8{0, 0, 1, 1, 1, 0}); !reflect.DeepEqual(got, []int{0, 1, 4, 3, 2, 5}) {
		t.Errorf("got %v", got)
	}
}
