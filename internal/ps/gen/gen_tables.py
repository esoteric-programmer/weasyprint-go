# Generates tables.go: python3 gen/gen_tables.py <glyphlist.txt> <8a.enc> <usyr.afm>
# glyphlist.txt is the Adobe Glyph List (BSD 3-Clause License, see
# LICENSE.agl); 8a.enc is Adobe StandardEncoding (public domain); the
# Symbol encoding comes from the built-in encoding of URW's usyr.afm.
import re, sys
agl, std_path, sym_path = sys.argv[1:4]
names = {}
for line in open(agl):
    if line.startswith('#') or ';' not in line: continue
    n, u = line.strip().split(';')
    cps = [int(x, 16) for x in u.split()]
    if len(cps) == 1 and n not in names:
        names[n] = cps[0]
std = re.findall(r'/([^\s\[\]]+)', open(std_path).read().split('[',1)[1])
assert len(std) == 256, len(std)
sym = ['.notdef'] * 256
for line in open(sym_path, encoding='latin-1'):
    m = re.match(r'C (\d+) ; WX \S+ ; N (\S+)', line)
    if m and int(m.group(1)) >= 0:
        sym[int(m.group(1))] = m.group(2)
# ISOLatin1Encoding (PLRM appendix E).
iso = ['.notdef'] * 256
for c in range(32, 127):
    iso[c] = std[c]
iso[0x27] = 'quoteright'; iso[0x60] = 'quoteleft'; iso[0x2d] = 'minus'
accents = ['dotlessi','grave','acute','circumflex','tilde','macron','breve','dotaccent','dieresis','.notdef','ring','cedilla','.notdef','hungarumlaut','ogonek','caron']
for i, n in enumerate(accents): iso[0x90 + i] = n
latin1 = ['space','exclamdown','cent','sterling','currency','yen','brokenbar','section','dieresis','copyright','ordfeminine','guillemotleft','logicalnot','hyphen','registered','macron',
 'degree','plusminus','twosuperior','threesuperior','acute','mu','paragraph','periodcentered','cedilla','onesuperior','ordmasculine','guillemotright','onequarter','onehalf','threequarters','questiondown',
 'Agrave','Aacute','Acircumflex','Atilde','Adieresis','Aring','AE','Ccedilla','Egrave','Eacute','Ecircumflex','Edieresis','Igrave','Iacute','Icircumflex','Idieresis',
 'Eth','Ntilde','Ograve','Oacute','Ocircumflex','Otilde','Odieresis','multiply','Oslash','Ugrave','Uacute','Ucircumflex','Udieresis','Yacute','Thorn','germandbls',
 'agrave','aacute','acircumflex','atilde','adieresis','aring','ae','ccedilla','egrave','eacute','ecircumflex','edieresis','igrave','iacute','icircumflex','idieresis',
 'eth','ntilde','ograve','oacute','ocircumflex','otilde','odieresis','divide','oslash','ugrave','uacute','ucircumflex','udieresis','yacute','thorn','ydieresis']
for i, n in enumerate(latin1): iso[0xa0 + i] = n
def arr(name, a):
    out = ['var %s = [256]string{' % name]
    line = '\t'
    for n in a:
        item = '"%s", ' % ('' if n == '.notdef' else n)
        if len(line) + len(item) > 100:
            out.append(line.rstrip()); line = '\t'
        line += item
    out.append(line.rstrip())
    out.append('}')
    return '\n'.join(out)
o = ['// Code generated by gen/gen_tables.py; DO NOT EDIT.', '', 'package ps', '',
     '// Encodings ("" is .notdef).', arr('standardEncoding', std), '', arr('isoLatin1Encoding', iso), '', arr('symbolEncoding', sym), '',
     '// aglNames maps glyph names to Unicode (Adobe Glyph List).', 'var aglNames = map[string]rune{']
for n in sorted(names):
    o.append('\t"%s": 0x%04X,' % (n, names[n]))
o.append('}')
open('tables.go', 'w').write('\n'.join(o) + '\n')
