package images

import (
	"bytes"
	"testing"
)

// The test sequence of the MQ coder (ITU-T T.88 Annex H.2, also used
// for JPEG 2000).
func TestMQDecoder(t *testing.T) {
	enc := []byte{0x84, 0xc7, 0x3b, 0xfc, 0xe1, 0xa1, 0x43, 0x04, 0x02, 0x20, 0x00, 0x00, 0x41, 0x0d, 0xbb, 0x86, 0xf4, 0x31, 0x7f, 0xff, 0x88, 0xff, 0x37, 0x47, 0x1a, 0xdb, 0x6a, 0xdf, 0xff, 0xac}
	want := []byte{0x00, 0x02, 0x00, 0x51, 0x00, 0x00, 0x00, 0xc0, 0x03, 0x52, 0x87, 0x2a, 0xaa, 0xaa, 0xaa, 0xaa, 0x82, 0xc0, 0x20, 0x00, 0xfc, 0xd7, 0x9e, 0xf6, 0xbf, 0x7f, 0xed, 0x90, 0x4f, 0x46, 0xa3, 0xbf}
	var m mqDecoder
	var cx mqContexts
	m.init(enc)
	got := make([]byte, len(want))
	for i := range got {
		for k := 0; k < 8; k++ {
			got[i] = got[i]<<1 | byte(m.decode(&cx, 0))
		}
	}
	if !bytes.Equal(got, want) {
		t.Errorf("got % x", got)
	}
}
